const CATEGORIES = ['boy', 'girl', 'thing', 'animal', 'plant', 'country', 'celeb'];

export default class BusAI {
    constructor(mockConn) {
        this.conn = mockConn;
        this.timers = [];
        this.currentLetter = '';
        this.aiAnswers = {};
        this.hasSentAnswers = false;

        setTimeout(() => {
            this.conn._sendToPlayer({
                type: 'global_ready',
                profile: { nickname: 'الذكاء الاصطناعي', avatar: 'robot' }
            });
        }, 500);
    }

    _addTimer(timer) {
        this.timers.push(timer);
        return timer;
    }

    _clearTimers() {
        this.timers.forEach(t => clearTimeout(t));
        this.timers = [];
    }

    _pickAnswer(letter, cat) {
        const dictLetter = ARABIC_DICT[letter] || ARABIC_DICT['أ'];
        const list = dictLetter[cat] || [];
        if (list.length > 0) {
            return list[Math.floor(Math.random() * list.length)];
        }
        return letter;
    }

    _generateRoundAnswers(letter) {
        const answers = {};
        CATEGORIES.forEach(cat => {
            // Small chance (10%) to omit a category on unusual letters, mimicking real players
            if (Math.random() < 0.08 && ['ذ', 'ث', 'ظ', 'ض'].includes(letter)) {
                answers[cat] = '';
            } else {
                answers[cat] = this._pickAnswer(letter, cat);
            }
        });
        return answers;
    }

    onMessage(msg) {
        if (!msg || !msg.type) return;

        switch (msg.type) {
            case 'start_round': {
                this._clearTimers();
                this.currentLetter = msg.letter || 'أ';
                this.aiAnswers = this._generateRoundAnswers(this.currentLetter);
                this.hasSentAnswers = false;

                // AI finishes round after 16 to 24 seconds and calls Bus!
                const completionDelay = 16000 + Math.random() * 8000;
                this._addTimer(setTimeout(() => {
                    if (!this.hasSentAnswers) {
                        this.hasSentAnswers = true;
                        // Call bus and send answers
                        this.conn._sendToPlayer({
                            type: 'bus',
                            caller: 'الذكاء الاصطناعي'
                        });
                        this.conn._sendToPlayer({
                            type: 'answers',
                            answers: this.aiAnswers
                        });
                    }
                }, completionDelay));
                break;
            }

            case 'bus': {
                // Opponent called bus!
                // AI immediately sends its answers so review begins right away
                if (!this.hasSentAnswers) {
                    this.hasSentAnswers = true;
                    this.conn._sendToPlayer({
                        type: 'answers',
                        answers: this.aiAnswers
                    });
                }
                break;
            }

            case 'answers': {
                // Opponent sent their answers
                // If AI hasn't replied yet, send immediately so review screen triggers
                if (!this.hasSentAnswers) {
                    this.hasSentAnswers = true;
                    this._addTimer(setTimeout(() => {
                        this.conn._sendToPlayer({
                            type: 'answers',
                            answers: this.aiAnswers
                        });
                    }, 400));
                }
                break;
            }

            case 'restart': {
                this._clearTimers();
                this.hasSentAnswers = false;
                break;
            }

            default:
                break;
        }
    }

    close() {
        this._clearTimers();
    }
}
