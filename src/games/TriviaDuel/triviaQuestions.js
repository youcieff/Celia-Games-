// Persistent tracking of recently seen questions across matches so questions never repeat in consecutive games!
let recentlyUsedIds = [];

export const getRandomTriviaQuiz = (count = 10) => {
    // Exclude recently seen questions if possible
    let availableQuestions = TRIVIA_QUESTIONS.filter(q => !recentlyUsedIds.includes(q.id));

    // If remaining questions are less than requested, reset the history pool
    if (availableQuestions.length < count) {
        recentlyUsedIds = [];
        availableQuestions = [...TRIVIA_QUESTIONS];
    }

    // High-entropy Fisher-Yates shuffle
    const pool = [...availableQuestions];
    for (let i = pool.length - 1; i > 0; i--) {
        const j = Math.floor(Math.random() * (i + 1));
        [pool[i], pool[j]] = [pool[j], pool[i]];
    }

    const selected = pool.slice(0, count);

    // Record selected IDs into recently used memory (max 100 recent to maintain variety)
    recentlyUsedIds = [...recentlyUsedIds, ...selected.map(q => q.id)].slice(-100);

    return selected;
};
